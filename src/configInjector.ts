function enforceLength(content: string): string {
  if (content.length <= 4000) return content;
  return content.slice(0, 3900).trimEnd() + "\n\n（注入内容已截断，完整版本请查看 AgentShell Profile 配置）";
}

function stripMarkers(content: string): string {
  return content.replace(BEGIN_MARKER, "").replace(END_MARKER, "");
}

function stripAllMarkerLines(content: string): string {
  return content
    .split(/\r?\n/)
    .filter((line) => line.trim() !== BEGIN_MARKER && line.trim() !== END_MARKER)
    .join("\n");
}

function findMarkerState(content: string): {
  beginIndexes: number[];
  endIndexes: number[];
  validPair?: { beginIndex: number; endIndex: number };
} {
  const beginIndexes = findAllIndexes(content, BEGIN_MARKER);
  const endIndexes = findAllIndexes(content, END_MARKER);
  const beginIndex = beginIndexes[0];
  const endIndex = endIndexes.find((candidate) => beginIndex !== undefined && candidate > beginIndex);
  const validPair = beginIndexes.length === 1 && endIndexes.length === 1 && beginIndex !== undefined && endIndex !== undefined
    ? { beginIndex, endIndex }
    : undefined;

  return { beginIndexes, endIndexes, validPair };
}

function findAllIndexes(content: string, marker: string): number[] {
  const indexes: number[] = [];
  let index = content.indexOf(marker);
  while (index !== -1) {
    indexes.push(index);
    index = content.indexOf(marker, index + marker.length);
  }
  return indexes;
}

function hasValidMcpEndpoint(content: string): boolean {
  const endpoint = content.match(/(?:地址|Endpoint)：?\s*`([^`]+)`/)?.[1];
  if (!endpoint) return false;
  if (endpoint.startsWith("stdio:")) return true;

  try {
    const url = new URL(endpoint);
    return url.protocol === "http:" || url.protocol === "https:";
  } catch {
    return endpoint.trim().length > 0;
  }
}

function truncate(value: string, maxLength: number): string {
  if (value.length <= maxLength) return value;
  return value.slice(0, maxLength - 20) + "（已截断）";
}

function formatDateTime(date: Date): string {
  return new Intl.DateTimeFormat("zh-CN", {
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
    hour12: false,
  }).format(date).replaceAll("/", "-");
}

function isNodeError(error: unknown): error is NodeJS.ErrnoException {
  return error instanceof Error && "code" in error;
}
