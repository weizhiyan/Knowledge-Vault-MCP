export async function injectAgentShellConfig(options: InjectionOptions): Promise<InjectionResult[]> {
  const targets = options.targets ?? ["claude", "agents"];
  const results: InjectionResult[] = [];

  for (const target of targets) {
    const relativePath = target === "claude" ? "CLAUDE.md" : "AGENTS.md";
    const filePath = path.join(options.projectRoot, relativePath);
    const content = target === "claude"
      ? generateClaudeMd(options)
      : generateAgentsMd(options);

    await fs.mkdir(path.dirname(filePath), { recursive: true });
    const writeResult = await writeWithMarker(filePath, content);
    results.push({ target, path: filePath, validation: validateInjectedContent(writeResult.block, writeResult.fileContent) });
  }

  return results;
}

export function generateClaudeMd(options: Omit<InjectionOptions, "projectRoot" | "targets">): string {
  const data = buildTemplateData(options);
  const sections = [
    `# AgentShell 配置\n> 由 AgentShell 自动生成，请勿手动修改标记块内的内容。\n> 最后更新：${data.updatedAt}\n\n---`,
    renderClaudeIdentity(data),
    renderClaudeSkills(data),
    renderClaudeMemory(data),
    renderClaudeKnowledge(data),
    renderClaudeConstraints(),
    renderClaudeMcp(data),
  ].filter(Boolean);

  return enforceLength(sections.join("\n\n"));
}

export function generateAgentsMd(options: Omit<InjectionOptions, "projectRoot" | "targets">): string {
  const data = buildTemplateData(options);
  const sections = [
    `# AgentShell Configuration\n> Auto-generated by AgentShell. Do not edit content within marker blocks.\n> Last updated: ${data.updatedAt}\n\n---`,
    renderAgentsIdentity(data),
    renderAgentsSkills(data),
    renderAgentsMemory(data),
    renderAgentsKnowledge(data),
    renderAgentsConstraints(),
    renderAgentsMcp(data),
  ].filter(Boolean);

  return enforceLength(sections.join("\n\n"));
}

export async function writeWithMarker(filePath: string, newContent: string): Promise<MarkerWriteResult> {
  const normalizedContent = stripMarkers(newContent).trim();
  const block = `${BEGIN_MARKER}\n${normalizedContent}\n${END_MARKER}`;

  let existing = "";
  try {
    existing = await fs.readFile(filePath, "utf-8");
  } catch (error) {
    if (isNodeError(error) && error.code === "ENOENT") {
      const fileContent = `${block}\n`;
      await fs.writeFile(filePath, fileContent, "utf-8");
      return { block, fileContent };
    }
    throw error;
  }

  const markerState = findMarkerState(existing);
  let fileContent: string;

  if (markerState.validPair) {
    const before = existing.slice(0, markerState.validPair.beginIndex);
    const after = existing.slice(markerState.validPair.endIndex + END_MARKER.length);
    fileContent = `${before}${block}${after}`;
  } else {
    const repaired = stripAllMarkerLines(existing).trimEnd();
    const separator = repaired.trim().length ? "\n\n" : "";
    fileContent = `${repaired}${separator}${block}\n`;
  }

  await fs.writeFile(filePath, fileContent, "utf-8");
  return { block, fileContent };
}

export function validateInjectedContent(content: string, fileContent = content): ValidationResult {
  const markerState = findMarkerState(fileContent);
  const checks = [
    {
      name: "包含身份定义",
      pass: content.includes("你现在扮演的角色是") || content.includes("You are acting as"),
    },
    {
      name: "至少有一条行为约束",
      pass: content.includes("必须遵守") || content.includes("Must:"),
    },
    {
      name: "包含唯一有效标记块",
      pass: markerState.beginIndexes.length === 1 && markerState.endIndexes.length === 1 && Boolean(markerState.validPair),
    },
    {
      name: "内容长度合理（不超过4000字）",
      pass: content.length <= 4000,
    },
    {
      name: "MCP Server 地址已填入",
      pass: hasValidMcpEndpoint(content),
    },
  ];

  const failures = checks.filter((check) => !check.pass).map((check) => check.name);
  return { valid: failures.length === 0, failures };
}

interface TemplateData {
  updatedAt: string;
  identity: Required<AgentProfile["identity"]>;
  skills: Array<Required<NonNullable<AgentProfile["skills"]>[number]>>;
  memory: { enabled: boolean; scope: NonNullable<AgentProfile["memoryScope"]> };
  knowledgeBases: Array<Required<NonNullable<AgentProfile["knowledgeBases"]>[number]>>;
  mcpServerUrl: string;
  mcpTools: McpToolDescription[];
}

function buildTemplateData(options: Omit<InjectionOptions, "projectRoot" | "targets">): TemplateData {
  const profile = options.profile;
  return {
    updatedAt: formatDateTime(options.updatedAt ?? new Date()),
    identity: {
      role: profile.identity.role,
      systemPrompt: truncate(profile.identity.systemPrompt, 600),
      guidelines: profile.identity.guidelines ?? [],
      responseStyle: profile.identity.responseStyle ?? "balanced",
      thinkingDepth: profile.identity.thinkingDepth ?? "standard",
    },
    skills: (profile.skills ?? [])
      .filter((skill) => skill.enabled !== false)
      .slice(0, 8)
      .map((skill) => ({
        name: skill.name,
        triggers: skill.triggers,
        description: skill.description,
        promptTemplate: skill.promptTemplate ?? "",
        requireConfirm: skill.requireConfirm ?? false,
        enabled: skill.enabled ?? true,
      })),
    memory: {
      enabled: (profile.memoryScope ?? "none") !== "none",
      scope: profile.memoryScope ?? "none",
    },
    knowledgeBases: (profile.knowledgeBases ?? []).slice(0, 5).map((kb) => ({
      id: kb.id,
      name: kb.name,
      description: kb.description,
      retrievalTopK: kb.retrievalTopK ?? 5,
      usageScenario: kb.usageScenario ?? "仅当用户明确聊到某个公司项目、产品、项目背景、功能、优势、定位或历史决策时检索；普通聊天、个人文章、草稿和非项目内容默认不检索。",
    })),
    mcpServerUrl: options.mcpServerUrl ?? `stdio: obsidian-knowledge-mcp`,
    mcpTools: (options.mcpTools ?? DEFAULT_MCP_TOOLS).slice(0, 10),
  };
}

function renderClaudeIdentity(data: TemplateData): string {
  const guidelines = data.identity.guidelines.length
    ? `\n### 行为准则\n${data.identity.guidelines.map((item, index) => `${index + 1}. ${item}`).join("\n")}`
    : "";

  return `## 🪪 当前身份\n\n你现在扮演的角色是：**${data.identity.role}**\n\n${data.identity.systemPrompt}${guidelines}\n\n### 参数设定\n- 回复风格：${mapResponseStyle(data.identity.responseStyle)}\n- 思考深度：${mapThinkingDepth(data.identity.thinkingDepth)}`;
}

function renderClaudeSkills(data: TemplateData): string {
  if (!data.skills.length) return "";

  return `## 🛠️ 可用技能\n\n你拥有以下技能，当用户的请求匹配触发条件时，主动使用对应技能：\n\n${data.skills.map((skill) => {
    const template = skill.promptTemplate ? `\n**执行模板：**\n${truncate(skill.promptTemplate, 500)}` : "";
    const confirm = skill.requireConfirm ? "\n⚠️ 执行前必须通过 AgentShell 向用户确认，不得自行决定执行。" : "";
    return `### ${skill.name}\n**触发条件：** ${skill.triggers.join("、")}\n**执行方式：** ${skill.description}${template}${confirm}`;
  }).join("\n\n---\n\n")}`;
}

function renderClaudeMemory(data: TemplateData): string {
  if (!data.memory.enabled) return "";

  const storeSection = data.memory.scope === "session" ? "" : `\n\n**写入记忆（对话结束时）：**\n- 工具：\`memory://store\`\n- 触发条件：用户明确表达了偏好、做出了重要决策、提供了新的背景信息\n- 禁止：不要把所有对话都写入记忆，只保留有价值的信息`;
  const scopeNote = data.memory.scope === "project"
    ? "\n- 当前作用域为项目级，记忆仅在当前工作区有效"
    : data.memory.scope === "user"
      ? "\n- 当前作用域为用户级，记忆跨所有项目共享"
      : "\n- 当前作用域为会话级，对话结束后记忆自动清空";

  return `## 🧠 记忆系统\n\n你可以通过以下方式访问和写入记忆：\n\n**读取记忆（对话开始时）：**\n- 工具：\`memory://recent?limit=5\`\n- 用途：了解最近几次对话的关键信息，避免用户重复解释\n\n**语义检索（需要历史信息时）：**\n- 工具：\`memory://search?q={关键词}\`\n- 用途：查找用户过去提到过的偏好、决策、背景信息\n- 原则：只在确实需要时检索，不要每轮对话都检索${storeSection}\n\n**记忆作用域：** ${data.memory.scope}${scopeNote}`;
}

